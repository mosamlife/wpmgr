    /**
     * The scenario fixture: what precheck answers for three inputs.
     */
    public static function layoutFixture(): string
    {
        $entry = self::entryText();
        $sha   = hash('sha256', $entry);
        $out   = [];
        foreach (self::scenarios() as $s) {
            $input = json_decode($s['input'], false, 32);
            self::assertIsObject($input);
            $r = PageCreateBuilder::validate($input);
            self::assertArrayHasKey('spec', $r, $s['name'] . ': ' . json_encode($r));
            $spec  = $r['spec'];
            $facts = [];
            $byId  = [];
            foreach (PageCreateBuilder::mediaIds($spec) as $id) {
                $facts[]   = $s['media'][$id];
                $byId[$id] = $s['media'][$id];
            }
            $content = PageCreateBuilder::render($spec, $byId);
            self::assertNull(PageCreateBuilder::retokenise($content), $s['name']);
            $base    = PageCreateBuilder::baseFingerprint($spec['post_type'], $facts);
            $preview = PageCreateBuilder::previewDigest($spec, $content);
            $pv      = [
                'post_type' => $spec['post_type'],
                'editor'    => $spec['editor'],
                'status'    => 'draft',
                'title'     => $spec['title'],
                'content'   => $content,
            ];
            if ($facts !== []) {
                $pv['media'] = $facts;
            }
            $out[] = [
                'name'             => $s['name'],
                'input'            => $s['input'],
                'media_ids'        => PageCreateBuilder::mediaIds($spec),
                'stored_title'     => PageCreateBuilder::storedTitle($spec['title']),
                'base_fingerprint' => $base,
                'preview_digest'   => $preview,
                'precheck_digest'  => hash('sha256', (string) json_encode([$sha, hash('sha256', $s['input']), $base, $preview])),
                'preview'          => $pv,
            ];
        }
        $doc = [
            'note'         => 'Generated by the agent (tests/PageCreateLayoutTest.php). Regenerate with WPMGR_WRITE_FIXTURES=1. '
                . 'Each case is what precheck answers for "input" on a site whose images have the facts in preview.media: '
                . 'base_fingerprint = sha256(json_encode(["new_post", post_type, [[id,url,filename,mime,width,height,modified_gmt], ...]])) '
                . 'in media_ids order (without images: sha256(json_encode(["new_post", post_type]))); '
                . 'preview_digest = sha256(json_encode([editor, post_type, "draft", title, content])); '
                . 'precheck_digest = sha256(json_encode([entry_sha256, sha256(input), base_fingerprint, preview_digest])). '
                . 'json_encode with default flags. preview.media is present only when the outline has an image.',
            'entry'        => $entry,
            'entry_sha256' => $sha,
            'limits'       => PageCreateBuilder::limits(),
            'cases'        => $out,
        ];

        return json_encode($doc, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
    }

