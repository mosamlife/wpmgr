    /**
     * The agent's verdict on one input text: "ok" or the refusal code.
     */
    public static function agentVerdict(string $inputText): string
    {
        $input = json_decode($inputText, false, 32);
        if (!is_object($input)) {
            return 'bad_input';
        }
        $r = PageCreateBuilder::validate($input);

        return isset($r['spec']) ? 'ok' : (string) $r['code'];
    }

