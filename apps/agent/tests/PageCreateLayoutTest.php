    /**
     * @param list<mixed> $outline
     */
    private static function page(array $outline, string $editor = 'wordpress_blocks', string $type = 'page'): string
    {
        return json_encode(['post_type' => $type, 'editor' => $editor, 'title' => 'T', 'outline' => $outline], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
    }

    /**
     * @param list<mixed> $outline
     * @return array{name:string,input:string,agent:string,go:string}
     */
    private static function c(string $name, string $agent, array $outline, string $editor = 'wordpress_blocks'): array
    {
        return self::raw($name, $agent, self::page($outline, $editor));
    }

    /**
     * @return array{name:string,input:string,agent:string,go:string}
     */
    private static function raw(string $name, string $agent, string $input, ?string $go = null): array
    {
        if ($go === null) {
            $go = $agent === 'ok' ? 'accept' : 'refuse';
        }

        return ['name' => $name, 'input' => $input, 'agent' => $agent, 'go' => $go];
    }

    /**
     * A text-rule refusal: the agent refuses, the control plane passes it on.
     *
     * @param list<mixed> $outline
     * @return array{name:string,input:string,agent:string,go:string}
     */
    private static function text(string $name, array $outline, string $editor = 'wordpress_blocks'): array
    {
        return self::raw($name, 'create_content_invalid', self::page($outline, $editor), 'accept');
    }

